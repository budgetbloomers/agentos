// Bundle the TCB-KB-V3 modules into worker/src/kb.mjs so the Worker's AI can
// answer business questions via layered retrieval (bootstrap always on + the
// module(s) relevant to the question). Run after any KB edit, then redeploy.
import fs from 'node:fs';
import path from 'node:path';

const dir = 'chatterbox-kb/data/modules';
const read = (f) => fs.readFileSync(path.join(dir, f), 'utf8').trim();

const MODULES = {
  bootstrap: read('01_BOOTSTRAP_ALWAYS_ON.yaml'),
  exec: read('00_EXECUTIVE_CORE.md'),
  strategy: read('02_COMPANY_STRATEGY_AND_BRAND.yaml'),
  people: read('03_PEOPLE_ORG_AND_DECISION_RIGHTS.yaml'),
  cleansales: read('04_CLEAN_SALES_OS_AND_AGENTOS.yaml'),
  systems: read('05_PLATFORMS_AND_SYSTEM_REGISTER.yaml'),
  data: read('06_DATA_ANALYTICS_AND_DASHBOARDS.yaml'),
  finance: read('07_FINANCE_ECONOMICS_AND_SCALE.yaml'),
  governance: read('08_GOVERNANCE_RISK_AI_AND_CONTROLS.yaml'),
  commercial: read('09_COMMERCIAL_DEMAND_AND_GROWTH.yaml'),
  decisions: read('10_OPEN_DECISIONS_AND_SOURCE_RULES.yaml'),
};

// keyword → module. bootstrap is always included; router adds the best match(es).
const ROUTER = {
  strategy: ['strategy', 'brand', 'position', 'value propos', 'vision', 'mission', 'service', 'client type', 'pricing', 'ambition'],
  people: ['who ', 'ctto', 'ceo', 'cfo', 'owner', 'role', 'nicholas', 'claudell', 'abigail', 'tiara', 'coo', 'team lead', 'exco', 'report to', 'decision right', 'accountab', 'org', 'people', 'staff', 'p0', 'p1'],
  cleansales: ['clean sale', 'agentos', 'lifecycle', 'funnel', 'recruit', 'cadence', 'passport', 'readiness', 'hot stove', 'scorecard', 'wfm', 'workforce management'],
  systems: ['system', 'platform', 'sys-', 'gate', 'gohighlevel', 'ghl', 'make', 'callx', 'vici', 'power bi', 'app ', 'register', 'g3', 'g4', 'integration'],
  data: ['data', 'analytics', 'dashboard', 'metric', 'upload', 'canonical', 'kpi dictionary', 'd01', 'd02', 'refresh', 'lineage', 'freshness'],
  finance: ['finance', 'econom', 'seat', 'cost', 'fund', 'revenue', 'margin', 'ebitda', '330', '370', 'contribution', 'cash', 'salary', 'r42', 'r34', 'investor', 'runway', 'per agent'],
  governance: ['governance', 'risk', ' ai ', 'autonomy', 'control', 'compliance', 'kill switch', 'incident', 'escalat', 'benefit', 'maturity', 'a1', 'a2', 'a3', 'six owner'],
  commercial: ['commercial', 'client acqui', 'demand', 'growth', 'bosch', 'product', 'lead suppli', 'campaign lifecycle', 'valuebox', 'autoscore', 'dealer', 'content', 'marketing'],
  decisions: ['conflict', 'decision', 'source priori', 'open ', 'unresolved', 'input required', 'backlog', 'reconcil'],
};

const js = `/* AUTO-GENERATED by tools/build-kb.mjs from chatterbox-kb/data/modules — do not edit by hand. */
export const KB_MODULES = ${JSON.stringify(MODULES)};
const ROUTER = ${JSON.stringify(ROUTER)};
/* Layered retrieval: bootstrap always on + up to 2 best-matching modules. */
export function retrieveKB(question) {
  const q = ' ' + String(question || '').toLowerCase() + ' ';
  const scored = Object.entries(ROUTER).map(([mod, kws]) => [mod, kws.reduce((n, k) => n + (q.includes(k) ? 1 : 0), 0)]).filter(([, n]) => n > 0).sort((a, b) => b[1] - a[1]);
  const picked = ['bootstrap'];
  if (!scored.length) picked.push('exec', 'decisions');
  else scored.slice(0, 2).forEach(([m]) => picked.push(m));
  return picked.map((m) => '### KB module: ' + m + '\\n' + KB_MODULES[m]).join('\\n\\n');
}
`;
fs.mkdirSync('worker/src', { recursive: true });
fs.writeFileSync('worker/src/kb.mjs', js);
const kb = (js.length / 1024).toFixed(0);
console.log('worker/src/kb.mjs written (' + kb + ' KB, ' + Object.keys(MODULES).length + ' modules).');
